#!/usr/bin/env python3
"""Notify the feed's WebSub hub after deployment; dry-run without network by default.

Only changed, committed RSS/Atom feeds are eligible. Before one publication POST,
each public feed must match the local generated bytes and its self/hub links.
The report records a hub receipt, never subscriber delivery, crawling or indexing.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
from urllib.error import HTTPError
from urllib.parse import urlencode, urlsplit
from urllib.request import HTTPRedirectHandler, Request, build_opener
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://sfmth.github.io/3d_printing_info/"
HUB = "https://pubsubhubbub.appspot.com/"
FEEDS = {"feed.xml": "application/rss+xml", "atom.xml": "application/atom+xml"}
ATOM = "{http://www.w3.org/2005/Atom}"
TIMEOUT = 20
MAX_FEED_BYTES = 2_000_000
RECEIPT_NOTE = ("A successful HTTP receipt acknowledges the publication notification only; "
                "it does not confirm subscriber delivery, crawling, indexing or ranking.")


class NoRedirects(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def git(repo: Path, *args: str) -> bytes:
    return subprocess.check_output(["git", *args], cwd=repo, stderr=subprocess.DEVNULL)


def resolve_commit(repo: Path, ref: str) -> str:
    value = git(repo, "rev-parse", "--verify", "--end-of-options", ref + "^{commit}").decode().strip()
    if not re.fullmatch(r"[0-9a-f]{40,64}", value):
        raise ValueError("Git did not return a commit hash")
    return value


def feed_url(filename: str) -> str:
    """Keep the notification set to the two canonical project feeds."""
    if filename not in FEEDS:
        raise ValueError(f"Unsupported feed file: {filename}")
    value = SITE + filename
    site, item = urlsplit(SITE), urlsplit(value)
    if (item.scheme != "https" or item.netloc != site.netloc
            or not item.path.startswith(site.path) or item.query or item.fragment):
        raise ValueError(f"Feed URL is outside the project: {value}")
    return value


def validate_feed(data: bytes, filename: str, url: str, hub: str = HUB) -> None:
    """Validate publisher discovery links without permitting arbitrary destinations."""
    if hub != HUB:
        raise ValueError("WebSub hub is not allowlisted")
    if url != feed_url(filename):
        raise ValueError(f"Noncanonical feed URL: {url}")
    if len(data) > MAX_FEED_BYTES:
        raise ValueError("Feed exceeds the local verification size limit")
    if re.search(br"<!\s*(?:DOCTYPE|ENTITY)\b", data, re.IGNORECASE):
        raise ValueError("Feed declarations must not contain a DTD or entity")
    root = ET.fromstring(data)
    if filename == "feed.xml":
        if root.tag != "rss" or root.get("version") != "2.0":
            raise ValueError("Expected an RSS 2.0 document")
        channels = root.findall("channel")
        if len(channels) != 1:
            raise ValueError("Expected exactly one RSS channel")
        links = channels[0].findall(ATOM + "link")
    else:
        if root.tag != ATOM + "feed":
            raise ValueError("Expected an Atom feed document")
        links = root.findall(ATOM + "link")
    self_links = [link for link in links if link.get("rel") == "self"]
    hub_links = [link for link in links if link.get("rel") == "hub"]
    if len(self_links) != 1 or self_links[0].get("href") != url:
        raise ValueError("Feed must have exactly one canonical rel=self link")
    if self_links[0].get("type") != FEEDS[filename]:
        raise ValueError("Feed rel=self type does not match its format")
    if len(hub_links) != 1 or hub_links[0].get("href") != hub:
        raise ValueError("Feed must have exactly one allowlisted rel=hub link")


def select_feeds(repo: Path, baseline_ref: str = "HEAD^", head_ref: str = "HEAD") -> tuple[list[dict], dict]:
    head = resolve_commit(repo, head_ref)
    try:
        baseline = resolve_commit(repo, baseline_ref)
    except subprocess.CalledProcessError:
        baseline = None
    if baseline:
        names = set(git(repo, "diff", "--name-only", "--no-renames", "-z", baseline,
                        head, "--", *FEEDS).decode().strip("\0").split("\0"))
        mode = "changed-committed-feeds"
    else:
        names = set(FEEDS)
        mode = "bootstrap-unavailable-history"
    selected = []
    for filename in FEEDS:
        local = (repo / filename).read_bytes()
        url = feed_url(filename)
        validate_feed(local, filename, url)
        try:
            committed = git(repo, "show", head + ":" + filename)
        except subprocess.CalledProcessError:
            committed = None
        if committed is None:
            # A local first build can be reviewed before committing. Submission
            # still requires the exact feed bytes to exist at the deployed SHA.
            names.add(filename)
            mode = "bootstrap-uncommitted-feeds"
        elif local != committed:
            raise ValueError(f"Local generated {filename} differs from commit {head}")
        if filename not in names:
            continue
        selected.append({"file": filename, "url": url,
                         "sha256": hashlib.sha256(local).hexdigest(),
                         "committed_sha256": hashlib.sha256(committed).hexdigest() if committed is not None else None,
                         "local_matches_commit": committed is not None,
                         "status": "not-verified"})
    return selected, {"commit": head, "baseline_commit": baseline, "selection": mode}


def publication_form(urls: list[str]) -> bytes:
    return urlencode([("hub.mode", "publish"), *[("hub.url", url) for url in urls]]).encode("ascii")


def preflight(opener, feed: dict, repo: Path) -> None:
    request = Request(feed["url"], headers={"User-Agent": "3d-printing-info-WebSub/1.0",
                                           "Accept": FEEDS[feed["file"]]})
    with opener.open(request, timeout=TIMEOUT) as response:
        feed["public_http_status"] = response.status
        if response.geturl() != feed["url"]:
            raise ValueError("Public feed response changed URL; redirects are not accepted")
        if response.status != 200:
            raise ValueError(f"Public feed returned HTTP {response.status}")
        data = response.read(MAX_FEED_BYTES + 1)
    feed["public_sha256"] = hashlib.sha256(data).hexdigest()
    if feed["public_sha256"] != feed["sha256"]:
        raise ValueError("Public feed does not match the generated deployment bytes; notification not sent")
    # Re-read locally to catch an artifact changing between selection and POST.
    local = (repo / feed["file"]).read_bytes()
    if hashlib.sha256(local).hexdigest() != feed["sha256"]:
        raise ValueError("Local feed changed during public verification; notification not sent")
    validate_feed(data, feed["file"], feed["url"])
    feed["status"] = "verified"


def publish(opener, feeds: list[dict]) -> int:
    request = Request(HUB, data=publication_form([feed["url"] for feed in feeds]),
                      method="POST", headers={"Content-Type": "application/x-www-form-urlencoded",
                                               "User-Agent": "3d-printing-info-WebSub/1.0"})
    with opener.open(request, timeout=TIMEOUT) as response:
        if response.geturl() != HUB:
            raise ValueError("Hub response changed URL; redirects are not accepted")
        status = response.status
    if not 200 <= status < 300:
        raise ValueError(f"Unexpected WebSub hub HTTP status: {status}")
    return status


def execute(repo: Path, report_file: Path, submit: bool = False,
            baseline_ref: str = "HEAD^", head_ref: str = "HEAD") -> int:
    report = {"site": SITE, "hub": HUB, "time": datetime.now(timezone.utc).isoformat(),
              "submit": submit, "status": "error", "feed_count": 0, "feeds": [],
              "urls": [], "notification": {"status": "not-sent", "http_status": None},
              "receipt_note": RECEIPT_NOTE}
    exit_code = 0
    try:
        feeds, selection = select_feeds(repo, baseline_ref, head_ref)
        report.update(selection, feeds=feeds, feed_count=len(feeds), urls=[feed["url"] for feed in feeds])
        if not submit:
            report["status"] = "dry-run"
            for feed in feeds:
                feed["status"] = "dry-run"
        elif not feeds:
            report["status"] = "no-changed-feeds"
        else:
            if any(not feed["local_matches_commit"] for feed in feeds):
                raise ValueError("Selected feeds must be committed before a publication notification")
            opener = build_opener(NoRedirects())
            for feed in feeds:
                try:
                    preflight(opener, feed, repo)
                except (OSError, ValueError, ET.ParseError) as error:
                    feed.update(status="verification-error", error=str(error))
                    if isinstance(error, HTTPError):
                        feed["public_http_status"] = error.code
                    raise
            report["notification"]["status"] = "attempted"
            status = publish(opener, feeds)
            report["notification"].update(status="received", http_status=status)
            for feed in feeds:
                feed.update(status="notification-received", notification_http_status=status)
            report["status"] = "notification-received"
    except (OSError, ValueError, ET.ParseError, subprocess.CalledProcessError) as error:
        exit_code = 1
        report["error"] = str(error)
        if report["notification"]["status"] == "attempted":
            report["notification"].update(status="error", error=str(error))
            if isinstance(error, HTTPError):
                report["notification"]["http_status"] = error.code
        print(f"WebSub notification failed: {error}", file=sys.stderr)
    finally:
        report_file.parent.mkdir(parents=True, exist_ok=True)
        report_file.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print(f"WebSub: {report['status']}; {report['feed_count']} feeds; report: {report_file}")
    return exit_code


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=ROOT)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--submit", action="store_true", help="Send publication notification; omitted by default")
    parser.add_argument("--base", default="HEAD^", help="Prior deployed tree comparison; defaults to the commit parent")
    parser.add_argument("--head", default="HEAD", help="Exact deployed commit; defaults to HEAD")
    args = parser.parse_args()
    return execute(args.repo, args.report, args.submit, args.base, args.head)


if __name__ == "__main__":
    sys.exit(main())
